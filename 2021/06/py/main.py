AOCEl = int
AOCInput = List[AOCEl]
AOCResult = int



def parse_el(s: str) -> AOCEl:
    return int(s)

def parse(s: str) -> AOCInput:
    return lm(parse_el, split(s, ','))

def a(inp: AOCInput) -> AOCResult:
    for _ in range(80):
        for i in range(len(inp)):
            if inp[i] == 0:
                inp[i] = 6
                inp.append(8)
            else:
                inp[i] -= 1
    
    return len(inp)

@ft.cache
def count_fishs(age: int, year: int) -> int:
    return 1 + sum(count_fishs(8, s) for s in range(year + age + 1, 256 + 1, 7))

def b0(inp: AOCInput) -> AOCResult:
    return sum(map(lambda f: count_fishs(f, 0), inp))

def fish_sum(start: int, age: int, days: List[int]) -> int:
    return 1 + sum(days[gday] for gday in range(start + age + 1, 256 + 1, 7))

def b(inp: AOCInput) -> AOCResult:
    days = [0 for _ in range(256 + 1)]
    for day in range(256, 0, -1):
        days[day] += fish_sum(day, 8, days)

    return sum(fish_sum(0, f, days) for f in inp)



